      assert.match(cli(), /^IGNORED=added$/m, 'the default .agents/forge/ is separate')
      assert.match(readFileSync(join(r.dir, '.git', 'info', 'exclude'), 'utf8'), /^\.agent\/forge\/\n\.agents\/forge\/\n$/m)
